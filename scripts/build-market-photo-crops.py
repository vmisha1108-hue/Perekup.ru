"""Validate reviewed image bounds and compile the browser lookup without editing photos."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
manifest = json.loads((ROOT / 'data/market-photo-crops.json').read_text())
lookup = {}
for photo in manifest['photos']:
    source = ROOT / photo['img']
    if hashlib.sha256(source.read_bytes()).hexdigest() != photo['sha256']:
        raise ValueError(f"Photo changed; review its crop again: {photo['img']}")
    width, height = photo['width'], photo['height']
    x, y, w, h = photo['region']
    if not all(isinstance(v, int) for v in [width, height, x, y, w, h]) or not (
        0 <= x < x + w <= width and 0 <= y < y + h <= height
        and w >= width * .75 and h >= height * .75
    ):
        raise ValueError(f"Invalid reviewed bounds: {photo['img']}")
    lookup[photo['img']] = [width, height, x, y, w, h]
(ROOT / 'market-photo-crops.js').write_text(
    "'use strict';\n// Generated by scripts/build-market-photo-crops.py; source photos stay unchanged.\n"
    'var MARKET_PHOTO_CROPS=' + json.dumps(lookup, separators=(',', ':')) + ';\n'
)
print(f"{manifest['auditedVehicles']} vehicles audited; {len(lookup)} reviewed image frames")
