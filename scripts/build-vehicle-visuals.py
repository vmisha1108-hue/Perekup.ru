"""Validate model photo annotations and compile the browser's immutable lookup."""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
manifest=json.loads((ROOT/'data/vehicle-visuals.json').read_text())
for src,digest in manifest['sources'].items():
 if hashlib.sha256((ROOT/src).read_bytes()).hexdigest()!=digest:raise ValueError('Review changed photo: '+src)
for key,photo in manifest['photos'].items():
 x,y,w,h=photo['region']
 if not (0<=x<x+w<=photo['width'] and 0<=y<y+h<=photo['height']):raise ValueError(key+' photo region')
 if not photo['body'] or len(photo['glass'])<2 or len(photo['wheels'])!=2:raise ValueError(key+' annotations')
 for polygon in photo['body']+photo['glass']+photo['exclude']:
  if len(polygon)<3 or any(not (0<=x<=1000 and 0<=y<=1000*h/w) for x,y in polygon):raise ValueError(key+' polygon bounds')
(ROOT/'vehicle-visuals.js').write_text("'use strict';\n// Generated by scripts/build-vehicle-visuals.py; original photographs are unchanged.\nvar VEHICLE_VISUALS="+json.dumps(manifest['photos'],ensure_ascii=False,separators=(',',':'))+';\n')
print(len(manifest['photos']),'model-specific Moscow photographs')
